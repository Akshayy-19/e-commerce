-- 01_schema.sql
-- E-Commerce Order Management System
-- Run as a normal project user/schema, not SYS or SYSTEM.

CREATE TABLE customers (
    customer_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR2(100) NOT NULL,
    email         VARCHAR2(150) NOT NULL UNIQUE,
    phone         VARCHAR2(20),
    city          VARCHAR2(60),
    created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE products (
    product_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name  VARCHAR2(120) NOT NULL,
    category      VARCHAR2(60),
    unit_price    NUMBER(10,2) NOT NULL,
    stock_qty     NUMBER(10) DEFAULT 0 NOT NULL,
    active_flag   CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT chk_products_price CHECK (unit_price >= 0),
    CONSTRAINT chk_products_stock CHECK (stock_qty >= 0),
    CONSTRAINT chk_products_active CHECK (active_flag IN ('Y','N'))
);

CREATE TABLE orders (
    order_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id    NUMBER NOT NULL,
    order_date     DATE DEFAULT SYSDATE NOT NULL,
    order_status   VARCHAR2(20) DEFAULT 'NEW' NOT NULL,
    order_total    NUMBER(12,2) DEFAULT 0 NOT NULL,
    payment_status VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id)
        REFERENCES customers(customer_id),
    CONSTRAINT chk_orders_status CHECK
        (order_status IN ('NEW','PROCESSING','SHIPPED','DELIVERED','CANCELLED')),
    CONSTRAINT chk_orders_payment CHECK
        (payment_status IN ('PENDING','PARTIAL','PAID')),
    CONSTRAINT chk_orders_total CHECK (order_total >= 0)
);

CREATE TABLE order_items (
    order_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      NUMBER NOT NULL,
    product_id    NUMBER NOT NULL,
    quantity      NUMBER(10) NOT NULL,
    unit_price    NUMBER(10,2) NOT NULL,
    line_total    NUMBER(12,2) NOT NULL,
    CONSTRAINT fk_items_order FOREIGN KEY (order_id)
        REFERENCES orders(order_id) ON DELETE CASCADE,
    CONSTRAINT fk_items_product FOREIGN KEY (product_id)
        REFERENCES products(product_id),
    CONSTRAINT uq_order_product UNIQUE (order_id, product_id),
    CONSTRAINT chk_items_quantity CHECK (quantity > 0),
    CONSTRAINT chk_items_price CHECK (unit_price >= 0),
    CONSTRAINT chk_items_total CHECK (line_total >= 0)
);

CREATE TABLE payments (
    payment_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     NUMBER NOT NULL,
    payment_date DATE DEFAULT SYSDATE NOT NULL,
    amount       NUMBER(12,2) NOT NULL,
    payment_mode VARCHAR2(20) NOT NULL,
    CONSTRAINT fk_payments_order FOREIGN KEY (order_id)
        REFERENCES orders(order_id) ON DELETE CASCADE,
    CONSTRAINT chk_payment_amount CHECK (amount > 0),
    CONSTRAINT chk_payment_mode CHECK
        (payment_mode IN ('CASH','CARD','UPI','NET_BANKING'))
);

CREATE INDEX idx_orders_customer ON orders(customer_id);
CREATE INDEX idx_items_order ON order_items(order_id);
CREATE INDEX idx_payments_order ON payments(order_id);

